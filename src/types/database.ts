// Hand-written types mirroring supabase/migrations/0001_init.sql and
// 0002_product_unit_size.sql. If the schema changes, update this alongside
// the migrations.

/** Matches the `products_unit_check` constraint in 0002_product_unit_size.sql. */
export const PRODUCT_UNITS = [
  "each",
  "kg",
  "g",
  "liter",
  "ml",
  "dozen",
  "pack",
  "box",
  "bag",
] as const;

export type ProductUnit = (typeof PRODUCT_UNITS)[number];

export type Category = {
  id: string;
  parent_id: string | null;
  name_en: string;
  name_ar: string;
  sort_order: number;
  created_at: string;
  image_path: string | null;
};

export type Product = {
  id: string;
  category_id: string;
  name_en: string;
  name_ar: string;
  description_en: string | null;
  description_ar: string | null;
  price: number;
  unit: ProductUnit;
  size: string | null;
  image_path: string | null;
  in_stock: boolean;
  /** Quantity on the shelves — fractional (e.g. 2.5 liters) only matters
   * when `allow_fraction` is true. See 0009_cashier_stock.sql. */
  stock_quantity: number;
  /** Admin switch: can this product be bought in fractions (milk) or only
   * whole units (eggs)? */
  allow_fraction: boolean;
  is_active: boolean;
  created_at: string;
  updated_at: string;
  updated_by: string | null;
};

/** Roles stored in `profiles.role` that the app understands. */
export type StaffRole = "admin" | "cashier";

export type Profile = {
  id: string;
  role: string;
  display_name: string | null;
  created_at: string;
};

export type InvoiceKind = "sale" | "purchase";

/** One line of an invoice. `unit_price` is the selling price for a sale and
 * the unit cost for a purchase. */
export type InvoiceLine = {
  id: string;
  invoice_id: string;
  product_id: string | null;
  product_name: string;
  quantity: number;
  unit_price: number;
};

/** A sale (customer purchase) or purchase (goods received) — see
 * 0009_cashier_stock.sql. */
export type Invoice = {
  id: string;
  /** Sequential receipt number (0010_invoice_number.sql). Optional so the
   * app still works — falling back to a short id — before that's applied. */
  number?: number;
  kind: InvoiceKind;
  total: number;
  note: string | null;
  created_by: string | null;
  cashier_name: string | null;
  created_at: string;
  /** Set when an admin voided it — it stays on record but no longer counts. */
  voided_at: string | null;
  invoice_lines: InvoiceLine[];
};

export type PaymentsBucket = {
  bucket: string;
  payments_in: number;
  payments_out: number;
};

export type StockValuation = {
  cost_value: number;
  retail_value: number;
  products_in_stock: number;
  products_missing_cost: number;
};

/** An extra photo beyond a product's own `image_path` cover image — see
 * 0008_product_images.sql. */
export type ProductImage = {
  id: string;
  product_id: string;
  image_path: string;
  sort_order: number;
  created_at: string;
};

/** A category with its direct subcategories attached, for nav trees. */
export type CategoryWithChildren = Category & {
  children: Category[];
};

/**
 * A temporary lower price for a product that expires on its own. At most
 * one per product — see 0003_discounts.sql.
 */
export type LimitedTimeDiscount = {
  id: string;
  product_id: string;
  new_price: number;
  starts_at: string;
  duration_days: number;
  /** Generated by the DB from `starts_at + duration_days`. */
  ends_at: string;
  created_at: string;
  updated_at: string;
  updated_by: string | null;
};

/** One "buy `min_quantity`+ for `price`" tier of a quantity discount. */
export type QuantityDiscountTier = {
  id: string;
  quantity_discount_id: string;
  min_quantity: number;
  price: number;
};

/** A product's tiered quantity pricing. At most one per product. */
export type QuantityDiscount = {
  id: string;
  product_id: string;
  created_at: string;
  updated_at: string;
  updated_by: string | null;
  /** Sorted ascending by `min_quantity`. */
  tiers: QuantityDiscountTier[];
};
